CREATE TABLE IF NOT EXISTS vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id VARCHAR(40) NOT NULL UNIQUE,
    registration_number TEXT,
    owner_name TEXT,
    device_id TEXT,
    device_token_hash TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS gps_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id VARCHAR(40) NOT NULL REFERENCES vehicles(vehicle_id),
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    speed DOUBLE PRECISION NOT NULL CHECK (speed BETWEEN 0 AND 300),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS gps_locations_vehicle_recorded_idx
    ON gps_locations (vehicle_id, recorded_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS accidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id VARCHAR(40) REFERENCES vehicles(vehicle_id),
    latitude DOUBLE PRECISION CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION CHECK (longitude BETWEEN -180 AND 180),
    impact_score INTEGER NOT NULL CHECK (impact_score BETWEEN 0 AND 100),
    severity TEXT NOT NULL,
    collision_type TEXT NOT NULL,
    detected_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    status TEXT NOT NULL DEFAULT 'Pending',
    confirmation_status TEXT NOT NULL DEFAULT 'pending',
    ai_event_id TEXT,
    event_type TEXT NOT NULL DEFAULT '',
    event_timestamp TEXT,
    confidence_json JSONB NOT NULL DEFAULT 'null'::jsonb,
    vehicle_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
    evidence JSONB NOT NULL DEFAULT '[]'::jsonb,
    CHECK ((latitude IS NULL) = (longitude IS NULL))
);

ALTER TABLE accidents ADD COLUMN IF NOT EXISTS ai_event_id TEXT;
ALTER TABLE accidents ADD COLUMN IF NOT EXISTS event_type TEXT NOT NULL DEFAULT '';
ALTER TABLE accidents ADD COLUMN IF NOT EXISTS event_timestamp TEXT;
ALTER TABLE accidents ADD COLUMN IF NOT EXISTS confidence_json JSONB NOT NULL DEFAULT 'null'::jsonb;
ALTER TABLE accidents ADD COLUMN IF NOT EXISTS vehicle_ids JSONB NOT NULL DEFAULT '[]'::jsonb;
ALTER TABLE accidents ADD COLUMN IF NOT EXISTS evidence JSONB NOT NULL DEFAULT '[]'::jsonb;

CREATE INDEX IF NOT EXISTS accidents_detected_at_idx
    ON accidents (detected_at DESC);
CREATE INDEX IF NOT EXISTS accidents_status_idx
    ON accidents (status, id);
CREATE UNIQUE INDEX IF NOT EXISTS accidents_ai_event_id_key
    ON accidents (ai_event_id);

CREATE TABLE IF NOT EXISTS sensor_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id VARCHAR(40) NOT NULL REFERENCES vehicles(vehicle_id),
    acceleration_x DOUBLE PRECISION NOT NULL,
    acceleration_y DOUBLE PRECISION NOT NULL,
    acceleration_z DOUBLE PRECISION NOT NULL,
    gyroscope_x DOUBLE PRECISION NOT NULL,
    gyroscope_y DOUBLE PRECISION NOT NULL,
    gyroscope_z DOUBLE PRECISION NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS sensor_readings_vehicle_recorded_idx
    ON sensor_readings (vehicle_id, recorded_at DESC);
